interface I18nState {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
}

export const useI18nStore = create<I18nState>()(
  persist(
    (set, get) => ({
      locale: 'en',
      setLocale: (locale: Locale) => set({ locale }),
      t: (key: string) => {
        const loc = get().locale;
        return translations[loc]?.[key] || translations.en[key] || key;
      },
    }),
    { name: 'mypos-i18n' }
  )
);

